import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";

if (process.env.VERCEL_ENV !== "preview") {
  console.log("Skipping launch-only lock export outside Vercel Preview.");
  process.exit(0);
}

const source = "package-lock.json";
const output = "public/__launch-lock";
if (!existsSync(source)) throw new Error("package-lock.json was not generated by npm install");
rmSync(output, { recursive: true, force: true });
mkdirSync(output, { recursive: true });
const text = readFileSync(source, "utf8");
const compressed = gzipSync(Buffer.from(text, "utf8"), { level: 9 });
const encoded = compressed.toString("base64");
writeFileSync(`${output}/manifest.json`, JSON.stringify({
  chars: text.length,
  sha256: createHash("sha256").update(text).digest("hex"),
  gzipBytes: compressed.length,
  base64Chars: encoded.length,
  data: encoded,
}));
console.log(`Launch-only lock export: ${text.length} chars in manifest.`);
