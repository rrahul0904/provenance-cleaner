import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const source = "package-lock.json";
const output = "public/__launch-lock";
if (!existsSync(source)) {
  throw new Error("package-lock.json was not generated by npm install");
}
rmSync(output, { recursive: true, force: true });
mkdirSync(output, { recursive: true });
const text = readFileSync(source, "utf8");
const chunkSize = 16_000;
const parts = [];
for (let offset = 0, index = 0; offset < text.length; offset += chunkSize, index += 1) {
  const name = `part-${String(index).padStart(3, "0")}.txt`;
  const chunk = text.slice(offset, offset + chunkSize);
  writeFileSync(`${output}/${name}`, chunk, "utf8");
  parts.push({ name, chars: chunk.length });
}
writeFileSync(`${output}/manifest.json`, JSON.stringify({ chars: text.length, sha256: createHash("sha256").update(text).digest("hex"), parts }, null, 2));
console.log(`Launch-only lock export: ${parts.length} part(s), ${text.length} chars.`);
